# Base R only. Run from repository root after audit_offline.py.
out <- 'reports/final/evaluation'
colors <- c('#225D4C', '#8AA786', '#E4BC76')
open_plot <- function(name, width=1600, height=1000) {
  png(file.path(out, name), width=width, height=height, res=150, type='quartz')
  par(bg='#FAFAF5', fg='#243B32', col.axis='#243B32', col.lab='#243B32', col.main='#243B32', family='sans', cex=1.1)
}
category <- read.csv(file.path(out,'categories.csv'))
category <- head(category, 12)
open_plot('category_distribution.png')
par(mar=c(6,17,5,2))
barplot(rev(category$product_assignments), names.arg=rev(vapply(category$category, function(x) paste(strwrap(x, width=35), collapse='\n'), character(1))), horiz=TRUE, las=1, col=colors[1], border=NA, xlab='Product-category assignments (overlapping)', main='Healthy U catalogue: twelve largest category labels')
mtext('All 5,512 records retained; a product can have multiple labels', side=1, line=4.5, cex=.8)
dev.off()
missing <- read.csv(file.path(out,'missing_data.csv'))
open_plot('missing_data.png')
par(mar=c(6,14,5,3))
barplot(rev(100*missing$missing_count/missing$total), names.arg=rev(missing$field), horiz=TRUE, las=1, col=colors[1], border=NA, xlim=c(0,110), xlab='Records with absent or unverified field (%)', main='Structured metadata coverage')
mtext('Unknown stock is missing verification; text descriptions do not prove ingredients or labels', side=1, line=4.5, cex=.75)
dev.off()
prices <- read.csv(file.path(out,'prices.csv'))
open_plot('price_distribution.png')
par(mar=c(6,5,5,2))
hist(prices$price_kes, breaks=40, col=colors[1], border='#FAFAF5', xlab='RRP (KES)', ylab='Product records', main='Healthy U listed retail prices (5,512 records)')
abline(v=median(prices$price_kes), col='#A66A20', lwd=3, lty=2)
legend('topright', legend=paste('Median KES', format(median(prices$price_kes), big.mark=',')), lty=2, lwd=3, col='#A66A20', bty='n')
mtext('Snapshot prices only; availability and live checkout prices are not verified', side=1, line=4.5, cex=.8)
dev.off()
retrieval <- read.csv(file.path(out,'retrieval_diagnostics.csv'))
open_plot('retrieval_latency.png')
par(mar=c(10,5,5,2))
boxplot(latency_ms ~ case_id, data=retrieval, las=2, col=colors[2], border=colors[1], ylab='Pure retrieval latency (milliseconds)', xlab='', main='Local fitted TF-IDF diagnostic latency')
mtext('13 scripted cases; 20 warm timed repeats each; no HTTP, Groq or UI time', side=3, line=.4, cex=.8)
dev.off()
